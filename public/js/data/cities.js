// Период летнего времени в РФ/СССР 1981–2010: последнее воскресенье марта → октября
export function dstSuggested(year, month, day) {
  if (year < 1981 || year > 2010) return false;
  const lastSun = (y, m) => {
    const d = new Date(Date.UTC(y, m + 1, 0));
    return d.getUTCDate() - ((d.getUTCDay() + 7) % 7);
  };
  const start = { m: 3, d: lastSun(year, 2) }, end = { m: 10, d: lastSun(year, 9) };
  const after = month > start.m || (month === start.m && day >= start.d);
  const before = month < end.m || (month === end.m && day < end.d);
  return after && before;
}
